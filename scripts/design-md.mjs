#!/usr/bin/env node
/**
 * Renders the generated half of `SYSTEM-DESIGN.md` from `docs/design/index.json`.
 *
 * Everything between the two markers below is derived from the tree: module
 * tables, every exported symbol with its signature and reference count, the
 * settings and their readers, the commands, the DOM names, and the record
 * example that the tests read. The authored half of the document is never
 * touched by this script — it is the only part a human writes, and
 * `docs-check.mjs` is what keeps the two honest about each other.
 *
 * Usage: node scripts/design-md.mjs [--verify]
 */

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const DOC = join(ROOT, "SYSTEM-DESIGN.md");
const INDEX = join(ROOT, "docs", "design", "index.json");

const BEGIN = "<!-- design:begin — generated by scripts/design-md.mjs; do not edit by hand -->";
const END = "<!-- design:end -->";

const cell = (text) => String(text).replace(/\|/g, "\\|").replace(/\n/g, " ");
const list = (items) => (items.length === 0 ? "—" : items.map((item) => `\`${item}\``).join("<br>"));
const short = (file) => file.replace(/^src\//, "");

function renderModules(index) {
  const rows = index.modules.map(
    (module) =>
      `| \`${module.file}\` | ${module.layer} | ${module.lines} | ${module.exports.length} | ${
        module.obsidian ? "yes" : "no"
      } |`
  );
  return [
    "### Modules",
    "",
    `${index.counts.modules} files, ${index.counts.exports} exported symbols, ${index.counts.testFiles} test files.`,
    "",
    "| file | layer | lines | exports | imports `obsidian` |",
    "| --- | --- | --- | --- | --- |",
    ...rows
  ].join("\n");
}

function renderSymbols(index) {
  const parts = ["### Symbols", "", "One table per module. `used by` is a textual reference from another file — a caller, a type annotation, a test — not a resolved call graph; this repository has no compiler API to resolve one, and the document must not claim what it cannot show.", ""];

  for (const module of index.modules) {
    parts.push(`#### \`${module.file}\``, "");
    if (module.doc) parts.push(module.doc.split("\n")[0], "");

    parts.push(
      "| symbol | kind | line | signature | used by | tested by |",
      "| --- | --- | --- | --- | --- | --- |"
    );
    for (const symbol of module.exports) {
      parts.push(
        `| \`${symbol.name}\` | ${symbol.kind} | ${symbol.line} | \`${cell(symbol.signature)}\` | ${cell(
          symbol.refs.length === 0 ? "—" : list(symbol.refs.map(short))
        )} | ${cell(symbol.testedBy.length === 0 ? "—" : list(symbol.testedBy))} |`
      );
    }
    parts.push("");
  }

  return parts.join("\n");
}

function renderDom(index) {
  const css = new Set([...index.css.defined, ...index.css.definedByScript]);
  const body = new Set(index.css.bodyClasses);
  const names = new Map();

  for (const module of index.modules) {
    for (const name of module.classes) {
      const entry = names.get(name) ?? { written: [], data: false };
      entry.written.push(module.file);
      names.set(name, entry);
    }
  }

  const rows = [...names].sort(([a], [b]) => a.localeCompare(b)).map(([name, entry]) => {
    const state = css.has(name) ? "styled" : body.has(name) ? "body state" : "hook";
    return `| \`${name}\` | ${state} | ${entry.written.length === 0 ? "—" : list(entry.written.map(short))} |`;
  });

  return [
    "### DOM names",
    "",
    "A name is a contract: a user's snippet may hang off any of them, so a rename is a breaking change and a `hook` is deliberate rather than dead. `styled` means a rule exists in `styles.css` or is generated by `src/ui/css.ts`; `body state` means `main.ts` toggles it on `<body>`; `hook` means Weaver writes it and nothing styles it — the tests or a user's CSS do.",
    "",
    "| name | state | written in |",
    "| --- | --- | --- |",
    ...rows,
    "",
    `**Dead CSS check.** Every class styled in \`styles.css\` must be written by the code. Unstyled rules right now: ${
      index.css.unused.length === 0 ? "none" : list(index.css.unused)
    }.`,
    "",
    "| attribute | written in |",
    "| --- | --- |",
    ...[...new Set(index.modules.flatMap((m) => m.dataAttrs))].sort().map((attribute) => {
      const modules = index.modules.filter((m) => m.dataAttrs.includes(attribute)).map((m) => short(m.file));
      return `| \`${attribute}\` | ${modules.map((m) => `\`${m}\``).join("<br>")} |`;
    })
  ].join("\n");
}

function renderSettings(index) {
  return [
    "### Settings",
    "",
    "| field | default | read in |",
    "| --- | --- | --- |",
    ...index.settings.map(
      (setting) =>
        `| \`${setting.field}\` | \`${cell(setting.value)}\` | ${
          setting.readers.length === 0 ? "—" : list(setting.readers.map(short))
        } |`
    ),
    "",
    "The names on disk are these names: `settings.ts#LEGACY_SETTING_KEYS` maps the v2 spellings and nothing else reads them."
  ].join("\n");
}

function renderCommands(index) {
  return [
    "### Commands",
    "",
    "| id | name | icon | hotkey |",
    "| --- | --- | --- | --- |",
    ...index.commands.map(
      (command) =>
        `| \`weaver:${command.id}\` | ${command.name} | \`${command.icon}\` | ${
          command.hotkey === null ? "—" : `\`${command.hotkey}\``
        } |`
    )
  ].join("\n");
}

function renderFixture(index) {
  if (index.fixture === null) return "### The record example\n\nNo fixture: `tests/fixtures/day-note.md` is missing.";
  return [
    "### The record example",
    "",
    `This is \`${index.fixture.file}\`, verbatim — the same bytes \`tests/record-format.test.ts\` parses. Its frontmatter agrees with its own text: \`applyDayStats\` returns it unchanged.`,
    "",
    "```markdown",
    index.fixture.text,
    "```"
  ].join("\n");
}

function renderDebt(index) {
  const perModule = index.modules
    .map((module) => ({
      file: module.file,
      tested: module.exports.filter((entry) => entry.testedBy.length > 0).length,
      total: module.exports.length
    }))
    .filter((row) => row.tested === 0);

  return [
    "### Coverage, as it actually is",
    "",
    "Derived, not asserted: a module whose exports no test names is listed here until a test names one. It is a report, not a gate — but it cannot go missing.",
    "",
    "| module | exports named by a test | exports |",
    "| --- | --- | --- |",
    ...perModule.map((row) => `| \`${row.file}\` | ${row.tested} | ${row.total} |`),
    "",
    `Modules with no symbol named by any test: ${perModule.length}.`
  ].join("\n");
}

function render(index) {
  return [
    BEGIN,
    "",
    renderModules(index),
    "",
    renderCommands(index),
    "",
    renderSettings(index),
    "",
    renderDom(index),
    "",
    renderFixture(index),
    "",
    renderDebt(index),
    "",
    renderSymbols(index),
    "",
    END
  ].join("\n");
}

const index = JSON.parse(readFileSync(INDEX, "utf8"));
const generated = render(index);
const doc = readFileSync(DOC, "utf8");
const begin = doc.indexOf(BEGIN);
const end = doc.indexOf(END);

if (begin === -1 || end === -1 || end < begin) {
  console.error(`SYSTEM-DESIGN.md must contain the markers:\n${BEGIN}\n${END}`);
  process.exit(1);
}

const next = `${doc.slice(0, begin)}${generated}${doc.slice(end + END.length)}`;

if (process.argv.includes("--verify")) {
  if (next !== doc) {
    console.error("SYSTEM-DESIGN.md's generated half is stale. Run: npm run design");
    process.exit(1);
  }
  console.log("generated half is current");
} else {
  writeFileSync(DOC, next);
  console.log("rewrote the generated half of SYSTEM-DESIGN.md");
}
